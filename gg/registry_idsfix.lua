local HEXD = "0123456789ABCDEF"
local function hex(n)
  if n == 0 then return "0" end
  local s = ""
  while n > 0 do
    local d = n % 16
    s = HEXD:sub(d + 1, d + 1) .. s
    n = (n - d) / 16
  end
  return s
end
local function u32(v) if v < 0 then return v + 4294967296 end return v end
local function s32(v) if v >= 2147483648 then return v - 4294967296 end return v end
local function ptrAt(w, i) return u32(w[i]) + (u32(w[i + 1]) % 16777216) * 4294967296 end

local function readWords(addr, n)
  local req = {}
  for i = 0, n - 1 do req[#req + 1] = { address = addr + i * 4, flags = gg.TYPE_DWORD } end
  local ok, res = pcall(gg.getValues, req)
  if not ok or not res then return nil end
  local w = {}
  for i = 1, #res do
    if res[i].value == nil then return nil end
    w[i] = u32(tonumber(res[i].value))
  end
  return w
end

local function readText(addr, n)
  local req = {}
  for i = 0, n - 1 do req[#req + 1] = { address = addr + i, flags = gg.TYPE_BYTE } end
  local ok, res = pcall(gg.getValues, req)
  if not ok or not res then return nil end
  local t = {}
  for i = 1, #res do
    local c = (tonumber(res[i].value) or 0) % 256
    if c == 0 then break end
    if c >= 32 and c < 127 then t[#t + 1] = string.char(c) else t[#t + 1] = "." end
  end
  return table.concat(t)
end

-- คีย์ std::string ของโหนด (w = หน้าต่าง 12 dword ที่ node)
local function keyOf(w)
  local b0 = w[5] % 256
  if b0 % 2 == 0 then
    local len = b0 / 2
    if len > 22 then return "?" end
    local t = {}
    for i = 1, len do
      t[i] = string.char(math.floor(w[5 + math.floor(i / 4)] / 2 ^ (8 * (i % 4))) % 256)
    end
    return table.concat(t)
  end
  local len, p = w[7], ptrAt(w, 9)
  if len > 64 or p == 0 then return "?" end
  return readText(p, len) or "?"
end

